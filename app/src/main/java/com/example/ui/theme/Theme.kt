    onSurface = SophisticatedTextPrimary,
    surfaceVariant = SophisticatedSurfaceDark,
    onSurfaceVariant = SophisticatedTextSecondary,
    outline = SophisticatedBorder,
    outlineVariant = SophisticatedBorder
